// Tool arguments that run an operation with its first example.
export function exampleArguments(entry: Tool, op: IROperation): JsonObject {
  const example = op.examples[0];
  if (example === undefined) throw new Error(`mcp: ${op.id} has no example`);
  const args: JsonObject = {};
  for (const name of entry.pathParams) args[name] = example.path[name];
  for (const name of entry.queryParams) if (example.query[name] !== undefined) args[name] = example.query[name];
  if (entry.body) args[BODY_ARGUMENT] = example.body;
  return args;
}

function toolsTest(ir: IR, tools: Tool[]): string {
  const cases = tools.map((entry, index) => {
    const op = ir.operations[index]!;
    const example = op.examples[0]!;
    const path = op.path.replace(/\{([^}]+)\}/g, (_, param: string) => encodeURIComponent(String(example.path[param])));
    const multipart = isObject(op.requestBody) && op.requestBody["contentMediaType"] === "multipart/form-data";
    const body = op.requestBody === null || multipart ? "null" : JSON.stringify(JSON.stringify(example.body));
    const annotations = JSON.stringify(entry.annotations);
    return `  { name: ${JSON.stringify(entry.name)}, operationId: ${JSON.stringify(op.id)}, annotations: ${annotations}, args: ${JSON.stringify(exampleArguments(entry, op))}, method: ${JSON.stringify(op.method)}, path: ${JSON.stringify(path)}, body: ${body} },`;
  });
  return `${HEADER}// Every tool called in process with the first example of its operation: a result
// without isError, and the method, path and JSON body of the request the SDK sent.
// tools/list gives one tool per operation, with its name and annotations.
import assert from "node:assert/strict";
import { createServer } from "node:http";
import type { AddressInfo } from "node:net";
import { after, before, test } from "node:test";
import { callTool, listTools } from "../src/server.ts";

interface Case {
  name: string;
  operationId: string;
  annotations: { readOnlyHint: boolean; destructiveHint: boolean; idempotentHint: boolean };
  args: Record<string, unknown>;
  method: string;
  path: string;
  // JSON body as text, or null when there is no JSON body.
  body: string | null;
}

const cases: Case[] = [
${cases.join("\n")}
];

const received: { method: string; path: string; body: string }[] = [];
const server = createServer((req, res) => {
  const chunks: Buffer[] = [];
  req.on("data", (chunk: Buffer) => chunks.push(chunk));
  req.on("end", () => {
    received.push({ method: req.method ?? "", path: (req.url ?? "").split("?")[0]!, body: Buffer.concat(chunks).toString() });
    res.writeHead(200, { "content-type": "application/json" });
    res.end('{"object":"list","has_more":false,"data":[]}');
  });
});

before(async () => {
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  process.env["RESEND_API_KEY"] = "re_paridad_test_9f8e7d6c5b4a39281706";
  process.env["RESEND_BASE_URL"] = \`http://127.0.0.1:\${(server.address() as AddressInfo).port}\`;
});

after(() => new Promise<void>((resolve) => server.close(() => resolve())));

test("tools/list has one tool per operation, with its name and annotations", () => {
  const tools = listTools();
  assert.equal(tools.length, ${tools.length});
  assert.deepEqual(
    tools.map((entry) => [entry.name, entry.annotations]),
    cases.map((c) => [c.name, c.annotations]),
  );
  for (const entry of tools) {
    assert.equal(entry.inputSchema["type"], "object");
    assert.equal(entry.inputSchema["$schema"], "https://json-schema.org/draft/2020-12/schema");
  }
});

for (const c of cases) {
  test(\`\${c.name} (\${c.operationId})\`, async () => {
    received.length = 0;
    const result = await callTool(c.name, c.args);
    assert.notEqual(result.isError, true, JSON.stringify(result));
    assert.equal(received.length, 1);
    const [request] = received;
    assert.equal(request!.method, c.method);
    assert.equal(request!.path, c.path);
    if (c.body !== null) assert.deepEqual(JSON.parse(request!.body), JSON.parse(c.body));
  });
}
`;
}
