// MCP server emitter (vault/CONTRACT.md §5, §6, D22, D28): writes mcp/ from the IR.
// The server, its transports and the argument validation are static templates in
// generator/templates/mcp/; the tool table (src/tools.ts) and the per-tool tests are
// generated from the IR. Every tool calls its method of the TypeScript SDK
// (paridad-resend).
import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type { IR, IROperation, IRParameter } from "../ir.ts";
import { SCHEMAS_REF, isObject, type JsonObject, type JsonSchema } from "../spec.ts";
import { TS_PACKAGE, TS_VERSION } from "./typescript.ts";

const TEMPLATES = resolve(import.meta.dirname, "../../templates/mcp");
const HEADER = "// Generated by paridad from ir/ir.json. Do not edit: change ir/overlay.yaml or generator/ and run make generate.\n";
const TEMPLATE_FILES = ["tsconfig.json", "src/main.ts", "src/server.ts", "test/server.test.ts"];
export const MCP_SDK_VERSION = "1.32.2";
const DIALECT = "https://json-schema.org/draft/2020-12/schema";
const DEFS_REF = "#/$defs/";
// Argument of the Idempotency-Key header, and of the request body.
export const IDEMPOTENCY_ARGUMENT = "idempotency_key";
export const BODY_ARGUMENT = "body";
const TOOL_NAME = /^[a-z0-9_-]{1,64}$/;
const SCHEMA_NAME = /^[A-Za-z0-9._-]+$/;

export interface Tool {
  name: string;
  operationId: string;
  description: string;
  // Without $defs: the server adds the component schemas named in `defs`.
  inputSchema: JsonObject;
  defs: string[];
  annotations: { readOnlyHint: boolean; destructiveHint: boolean; idempotentHint: boolean };
  // Resource property and method of the SDK client.
  sdk: [string, string];
  pathParams: string[];
  queryParams: string[];
  // Header parameters other than Idempotency-Key, whose arguments are named as the header.
  headerParams: string[];
  body: boolean;
  // Top-level body properties of format binary, sent as files of a multipart body.
  binary: string[];
  idempotency: boolean;
}

export function emitMcp(ir: IR, outDir: string): void {
  const root = join(outDir, "mcp");
  // node_modules (pnpm) survives; everything the emitter owns is rewritten.
  for (const owned of ["src", "test", "package.json", "tsconfig.json"]) rmSync(join(root, owned), { recursive: true, force: true });
  mkdirSync(join(root, "src"), { recursive: true });
  mkdirSync(join(root, "test"), { recursive: true });
  for (const file of TEMPLATE_FILES) cpSync(join(TEMPLATES, file), join(root, file));
  const safeMethods = safeMethodsOf(ir);
  const tools = ir.operations.map((op) => tool(op, ir.schemas, safeMethods));
  const seen = new Set<string>();
  for (const { name, operationId } of tools) {
    if (seen.has(name)) throw new Error(`mcp: tool ${name} of ${operationId} is generated twice`);
    seen.add(name);
  }
  const used = new Set(tools.flatMap((entry) => entry.defs));
  const defs = Object.fromEntries([...used].sort().map((name) => [name, toDefsRefs(ir.schemas[name]!)]));
  writeFileSync(join(root, "package.json"), packageJson());
  writeFileSync(join(root, "src/tools.ts"), toolsModule(tools, defs));
  writeFileSync(join(root, "test/tools.test.ts"), toolsTest(ir, tools));
}

function packageJson(): string {
  const manifest = {
    name: "paridad-mcp",
    version: TS_VERSION,
    description: "MCP server of the Resend API generated by paridad from the pinned OpenAPI specification.",
    license: "MIT",
    type: "module",
    bin: { "paridad-mcp": "./src/main.ts" },
    files: ["src"],
    engines: { node: ">=26" },
    scripts: { check: "tsc --strict --noEmit -p .", test: "node --test" },
    dependencies: {
      "@modelcontextprotocol/sdk": MCP_SDK_VERSION,
      ajv: "8.20.0",
      [TS_PACKAGE]: "workspace:*",
    },
    devDependencies: { "@types/node": "26.6.6", typescript: "7.0.2" },
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

// Methods that are safe to retry by policy (§5.3); they make a tool idempotent.
function safeMethodsOf(ir: IR): Set<string> {
  const methods = ir.policy["safe_methods"];
  if (!Array.isArray(methods) || !methods.every((method) => typeof method === "string")) throw new Error("mcp: policy.safe_methods is not a list of methods");
  return new Set(methods);
}

export function tool(op: IROperation, schemas: Record<string, JsonSchema>, safeMethods: Set<string>): Tool {
  const name = op.names.mcp;
  if (!TOOL_NAME.test(name)) throw new Error(`mcp: names.mcp ${name} of ${op.id} is not [a-z0-9_-]`);
  const sdk = op.names.ts.split(".");
  if (sdk.length !== 2) throw new Error(`mcp: names.ts ${op.names.ts} of ${op.id} is not resource.method`);
  const headers = op.headerParams.filter((parameter) => parameter.name.toLowerCase() !== "idempotency-key");

  const properties: Record<string, JsonSchema> = {};
  const required: string[] = [];
  const add = (argument: string, schema: JsonSchema, isRequired: boolean): void => {
    if (properties[argument] !== undefined) throw new Error(`mcp: argument ${argument} of ${op.id} collides with another argument`);
    properties[argument] = schema;
    if (isRequired) required.push(argument);
  };
  for (const parameter of op.pathParams) add(parameter.name, parameterSchema(parameter), true);
  for (const parameter of op.queryParams) add(parameter.name, parameterSchema(parameter), parameter.required);
  for (const parameter of headers) add(parameter.name, parameterSchema(parameter), parameter.required);
  if (op.idempotency) {
    // No maxLength here: a key out of 1 to 256 characters reaches the SDK, which
    // answers invalid_idempotency_key like every other surface (§5.2, C10).
    add(IDEMPOTENCY_ARGUMENT, { type: "string", description: "Sent as Idempotency-Key, the same on every attempt; 1 to 256 characters." }, false);
  }
  if (op.requestBody !== null) add(BODY_ARGUMENT, op.requestBody, true);

  const inputSchema: JsonObject = { $schema: DIALECT, type: "object", properties: toDefsRefs(properties) };
  if (required.length > 0) inputSchema["required"] = required;
  inputSchema["additionalProperties"] = false;
  const binary = op.requestBody === null ? [] : binaryProperties(op.requestBody, schemas);
  return {
    name,
    operationId: op.id,
    description: description(op, binary),
    inputSchema,
    defs: [...referenced(properties, schemas)].sort(),
    annotations: {
      readOnlyHint: op.readOnly,
      destructiveHint: op.destructive,
      idempotentHint: safeMethods.has(op.method),
    },
    sdk: sdk as [string, string],
    pathParams: op.pathParams.map((parameter) => parameter.name),
    queryParams: op.queryParams.map((parameter) => parameter.name),
    headerParams: headers.map((parameter) => parameter.name),
    body: op.requestBody !== null,
    binary,
    idempotency: op.idempotency,
  };
}

// The parameter schema as is, with the parameter description when it has none.
function parameterSchema(parameter: IRParameter): JsonSchema {
  if (parameter.description === null || !isObject(parameter.schema) || parameter.schema["description"] !== undefined) return parameter.schema;
  return { ...parameter.schema, description: parameter.description };
}

function description(op: IROperation, binary: string[]): string {
  const lines = [op.summary ?? op.id, "", `operationId: ${op.id} (${op.method} ${op.path})`];
  if (binary.length > 0) lines.push(`File fields of the body (${binary.join(", ")}) take the content of the file as text.`);
  return lines.join("\n");
}

// Names of the component schemas a value references, directly or through others.
function referenced(value: unknown, schemas: Record<string, JsonSchema>, found = new Set<string>()): Set<string> {
  if (Array.isArray(value)) for (const item of value) referenced(item, schemas, found);
  else if (isObject(value)) {
    for (const [key, child] of Object.entries(value)) {
      if (key === "$ref" && typeof child === "string") {
        const name = schemaName(child, schemas);
        if (!found.has(name)) {
          found.add(name);
          referenced(schemas[name], schemas, found);
        }
      } else referenced(child, schemas, found);
    }
  }
  return found;
}

function schemaName(ref: string, schemas: Record<string, JsonSchema>): string {
  const name = ref.startsWith(SCHEMAS_REF) ? ref.slice(SCHEMAS_REF.length) : "";
  if (schemas[name] === undefined || !SCHEMA_NAME.test(name)) throw new Error(`mcp: $ref ${ref} is not a component schema`);
  return name;
}

// #/schemas/<name> of the IR becomes #/$defs/<name> of the input schema.
function toDefsRefs<T>(value: T): T {
  if (Array.isArray(value)) return value.map(toDefsRefs) as T;
  if (!isObject(value)) return value;
  return Object.fromEntries(
    Object.entries(value).map(([key, child]) => [
      key,
      key === "$ref" && typeof child === "string" && child.startsWith(SCHEMAS_REF) ? `${DEFS_REF}${child.slice(SCHEMAS_REF.length)}` : toDefsRefs(child),
    ]),
  ) as T;
}

function deref(schema: JsonSchema, schemas: Record<string, JsonSchema>): JsonSchema {
  for (let depth = 0; isObject(schema) && typeof schema["$ref"] === "string" && depth < 32; depth++) schema = schemas[schemaName(schema["$ref"], schemas)]!;
  return schema;
}

// Top-level body properties of format binary (only multipart bodies have them).
function binaryProperties(body: JsonSchema, schemas: Record<string, JsonSchema>): string[] {
  const found: string[] = [];
  const visit = (node: JsonSchema, depth: number): void => {
    node = deref(node, schemas);
    if (!isObject(node) || depth > 32) return;
    if (isObject(node["properties"])) {
      for (const [name, property] of Object.entries(node["properties"])) {
        const resolved = deref(property as JsonSchema, schemas);
        if (isObject(resolved) && resolved["format"] === "binary") found.push(name);
      }
    }
    if (Array.isArray(node["allOf"])) for (const member of node["allOf"] as JsonSchema[]) visit(member, depth + 1);
  };
  visit(body, 0);
  return found;
}

function toolsModule(tools: Tool[], defs: Record<string, JsonSchema>): string {
  return `${HEADER}// One tool per operation of the IR: <resource>_<action>, with the literal operationId,
// its input schema (JSON Schema 2020-12), annotations and the SDK method it calls.
import type { Tool } from "./server.ts";

export const SERVER_VERSION = ${JSON.stringify(TS_VERSION)};

// Component schemas of the IR referenced by the input schemas as #/$defs/<name>.
export const DEFS: Readonly<Record<string, unknown>> = ${JSON.stringify(defs, null, 2)};

export const TOOLS: readonly Tool[] = ${JSON.stringify(tools, null, 2)};
`;
}

