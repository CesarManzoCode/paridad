      const path = op.path.replace(/\{([^}]+)\}/g, (_, param: string) => encodeURIComponent(String(example.path[param])));
      if (op.requestBody !== null) args.push(json(example.body));
      if (op.queryParams.length > 0) args.push(json(example.query));
