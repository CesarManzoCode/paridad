// resources, the client and the per-operation tests are generated from the IR.
import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type { IR, IROperation, IRParameter } from "../ir.ts";
import { SCHEMAS_REF, isObject, type JsonObject, type JsonSchema } from "../spec.ts";

export const PY_PACKAGE = "paridad-resend";
export const PY_MODULE = "paridad_resend";
export const PY_VERSION = "0.0.0-dev";
const TEMPLATES = resolve(import.meta.dirname, "../../templates/python");
const HEADER = "# Generated by paridad from ir/ir.json. Do not edit: change ir/overlay.yaml or generator/ and run make generate.\n";
const IDEMPOTENCY_HEADER = "idempotency-key";
// Names that schemas.py itself binds.
const RESERVED_TYPE_NAMES = new Set(["Any", "Literal", "NoReturn", "TypeAlias", "TypedDict", "annotations"]);
const RESERVED_PARAMETERS = new Set(["self", "body", "query", "idempotency_key"]);
const PY_KEYWORDS = new Set(
  "False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield".split(
    " ",
  ),
);

const SCALARS = new Set(["str", "int", "float", "bool", "bytes", "None"]);

export function emitPython(ir: IR, outDir: string): void {
  const root = join(outDir, "sdks/python");
  const pkg = join(root, "src", PY_MODULE);
  for (const owned of ["src", "tests", "pyproject.toml"]) rmSync(join(root, owned), { recursive: true, force: true });
  mkdirSync(pkg, { recursive: true });
  mkdirSync(join(root, "tests"), { recursive: true });
  cpSync(join(TEMPLATES, "src", PY_MODULE, "_runtime.py"), join(pkg, "_runtime.py"));
  cpSync(join(TEMPLATES, "src", PY_MODULE, "py.typed"), join(pkg, "py.typed"));
  cpSync(join(TEMPLATES, "tests/test_runtime.py"), join(root, "tests/test_runtime.py"));
  writeFileSync(join(root, "pyproject.toml"), pyproject());
  writeFileSync(join(pkg, "_policy.py"), policyModule(ir));
  const types = new PyTypes(ir.schemas);
  const resources = groupResources(ir.operations);
  // Resources first: their query, body and response types land in schemas.py too.
  const resourcesSource = resourcesModule(resources, types);
  writeFileSync(join(pkg, "resources.py"), resourcesSource);
  writeFileSync(join(pkg, "schemas.py"), types.module());
  writeFileSync(join(pkg, "__init__.py"), initModule(resources));
  writeFileSync(join(root, "tests/test_operations.py"), operationsTest(resources));
}

