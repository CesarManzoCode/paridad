// CLI emitter (vault/CONTRACT.md §5, §6, D27): writes cli/ from the IR. The argument
// parsing, output contract, `config show`, `contract-check` and React Email loading
// are static templates in generator/templates/cli/; the command table
// (src/commands.ts) and the per-command tests are generated from the IR. Every
// command calls the TypeScript SDK (paridad-resend).
import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type { IR, IROperation, IRParameter } from "../ir.ts";
import { SCHEMAS_REF, isObject, type JsonSchema } from "../spec.ts";
import { TS_PACKAGE, TS_VERSION } from "./typescript.ts";

const TEMPLATES = resolve(import.meta.dirname, "../../templates/cli");
const HEADER = "// Generated by paridad from ir/ir.json. Do not edit: change ir/overlay.yaml or generator/ and run make generate.\n";
const TEMPLATE_FILES = ["tsconfig.json", "src/main.ts", "src/cli.ts", "test/cli.test.ts", "test/fixtures/welcome.tsx"];
// Flags every command may take, and commands of the template.
const RESERVED_FLAGS = new Set(["body", "json", "all", "help", "idempotency-key", "timeout-ms", "react", "react-props"]);
const RESERVED_RESOURCES = new Set(["config", "contract-check"]);
const TOKEN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

// How the text of a flag becomes a value: `string` as is, `json` parsed as JSON,
// `auto` parsed as JSON only when it starts with [ or {, `binary` read from the file it names.
export type FlagKind = "string" | "json" | "auto" | "binary";

export interface Flag {
  flag: string;
  name: string;
  kind: FlagKind;
  required: boolean;
  description: string | null;
}

export interface Command {
  operationId: string;
  resource: string;
  action: string;
  summary: string | null;
  method: string;
  path: string;
  // Resource property and method of the SDK client.
  sdk: [string, string];
  pathParams: Flag[];
  queryParams: Flag[];
  // Flags of the top-level body properties; null when the operation has no body.
  body: { flags: Flag[] } | null;
  idempotency: boolean;
  paginated: boolean;
  react: boolean;
}

export function emitCli(ir: IR, outDir: string): void {
  const root = join(outDir, "cli");
  // node_modules (pnpm) survives; everything the emitter owns is rewritten.
  for (const owned of ["src", "test", "package.json", "tsconfig.json"]) rmSync(join(root, owned), { recursive: true, force: true });
  mkdirSync(join(root, "src"), { recursive: true });
  mkdirSync(join(root, "test/fixtures"), { recursive: true });
  for (const file of TEMPLATE_FILES) cpSync(join(TEMPLATES, file), join(root, file));
  const commands = ir.operations.map((op) => command(op, ir.schemas));
  const seen = new Set<string>();
  for (const { resource, action, operationId } of commands) {
    if (seen.has(`${resource} ${action}`)) throw new Error(`cli: command ${resource} ${action} of ${operationId} is generated twice`);
    seen.add(`${resource} ${action}`);
  }
  writeFileSync(join(root, "package.json"), packageJson());
  writeFileSync(join(root, "src/commands.ts"), commandsModule(commands));
  writeFileSync(join(root, "test/commands.test.ts"), commandsTest(ir, commands));
}

function packageJson(): string {
  const manifest = {
    name: "paridad-cli",
    version: TS_VERSION,
    description: "Command line client of the Resend API generated by paridad from the pinned OpenAPI specification.",
    license: "MIT",
    type: "module",
    bin: { paridad: "./src/main.ts" },
    files: ["src"],
    engines: { node: ">=26" },
    scripts: { check: "tsc --strict --noEmit -p .", test: "node --test" },
    dependencies: {
      "@react-email/render": "2.3.1",
      esbuild: "0.28.2",
      [TS_PACKAGE]: "workspace:*",
      react: "19.3.1",
      "react-dom": "19.3.1",
    },
    devDependencies: { "@types/node": "26.6.6", "@types/react": "19.3.0", typescript: "7.0.2" },
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

export function command(op: IROperation, schemas: Record<string, JsonSchema>): Command {
  const match = /^paridad (\S+) (\S+)$/.exec(op.names.cli);
  if (match === null || !TOKEN.test(match[1]!) || !TOKEN.test(match[2]!)) throw new Error(`cli: names.cli ${op.names.cli} of ${op.id} is not paridad <resource> <action>`);
  const [, resource, action] = match as unknown as [string, string, string];
  if (RESERVED_RESOURCES.has(resource)) throw new Error(`cli: resource ${resource} of ${op.id} collides with a command of the CLI`);
  const sdk = op.names.ts.split(".");
  if (sdk.length !== 2) throw new Error(`cli: names.ts ${op.names.ts} of ${op.id} is not resource.method`);
  const pathParams = op.pathParams.map((parameter) => parameterFlag(parameter, schemas));
  const queryParams = op.queryParams.map((parameter) => parameterFlag(parameter, schemas));
  let body: Command["body"] = null;
  if (op.requestBody !== null) {
    const { properties, required } = topLevel(op.requestBody, schemas);
    body = {
      flags: Object.entries(properties).map(([name, schema]) => ({
        flag: flagName(name, op),
        name,
        kind: flagKind(schema, schemas),
        required: required.has(name),
        description: isObject(schema) && typeof schema["description"] === "string" ? firstLine(schema["description"]) : null,
      })),
    };
  }
  const flags = [...pathParams, ...queryParams, ...(body?.flags ?? [])].map((flag) => flag.flag);
  for (const flag of flags) {
    if (RESERVED_FLAGS.has(flag) || flags.indexOf(flag) !== flags.lastIndexOf(flag)) throw new Error(`cli: flag --${flag} of ${op.id} collides with another flag`);
  }
  return {
    operationId: op.id,
    resource,
    action,
    summary: op.summary,
    method: op.method,
    path: op.path,
    sdk: sdk as [string, string],
    pathParams,
    queryParams,
    body,
    idempotency: op.idempotency,
    paginated: op.pagination !== null,
    react: op.id === "emails/send",
  };
}

function parameterFlag(parameter: IRParameter, schemas: Record<string, JsonSchema>): Flag {
  return {
    flag: flagName(parameter.name, null),
    name: parameter.name,
    kind: flagKind(parameter.schema, schemas),
    required: parameter.required,
    description: parameter.description === null ? null : firstLine(parameter.description),
  };
}

function flagName(name: string, op: IROperation | null): string {
  const flag = name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  if (!TOKEN.test(flag)) throw new Error(`cli: ${name}${op === null ? "" : ` of ${op.id}`} gives no flag name`);
  return flag;
}

function firstLine(text: string): string {
  return text.trim().split("\n")[0]!.trim();
}

function deref(schema: JsonSchema, schemas: Record<string, JsonSchema>): JsonSchema {
  for (let depth = 0; isObject(schema) && typeof schema["$ref"] === "string" && depth < 32; depth++) {
    const ref = schema["$ref"];
    if (!ref.startsWith(SCHEMAS_REF) || schemas[ref.slice(SCHEMAS_REF.length)] === undefined) throw new Error(`cli: $ref ${ref} is not a component schema`);
    schema = schemas[ref.slice(SCHEMAS_REF.length)]!;
  }
  return schema;
}

// Top-level properties of a body schema, following $ref and allOf. A body that is
// not an object (emails/send-batch is an array) has none and is given with --body.
function topLevel(schema: JsonSchema, schemas: Record<string, JsonSchema>): { properties: Record<string, JsonSchema>; required: Set<string> } {
  const properties: Record<string, JsonSchema> = {};
  const required = new Set<string>();
  const visit = (node: JsonSchema, depth: number): void => {
    node = deref(node, schemas);
    if (!isObject(node) || depth > 32) return;
    if (isObject(node["properties"])) Object.assign(properties, node["properties"]);
    if (Array.isArray(node["required"])) for (const name of node["required"]) if (typeof name === "string") required.add(name);
    if (Array.isArray(node["allOf"])) for (const member of node["allOf"] as JsonSchema[]) visit(member, depth + 1);
  };
  visit(schema, 0);
  return { properties, required };
}

// The JSON types a value of the schema can have; null when the schema does not say.
function jsonTypes(schema: JsonSchema, schemas: Record<string, JsonSchema>, depth = 0): Set<string> | null {
  schema = deref(schema, schemas);
  if (!isObject(schema) || depth > 32) return null;
  const typeOf = (value: unknown): string => (value === null ? "null" : Array.isArray(value) ? "array" : typeof value);
  if ("const" in schema) return new Set([typeOf(schema["const"])]);
  if (Array.isArray(schema["enum"])) return new Set(schema["enum"].map(typeOf));
  const declared = typeof schema["type"] === "string" ? [schema["type"]] : Array.isArray(schema["type"]) ? (schema["type"] as unknown[]) : null;
  if (declared !== null) return new Set(declared.map((type) => (type === "integer" ? "number" : String(type))));
  for (const key of ["oneOf", "anyOf", "allOf"]) {
    if (!Array.isArray(schema[key])) continue;
    const found = new Set<string>();
    for (const branch of schema[key] as JsonSchema[]) {
      const types = jsonTypes(branch, schemas, depth + 1);
      if (types === null) return null;
      for (const type of types) found.add(type);
    }
    return found;
  }
  if (schema["properties"] !== undefined) return new Set(["object"]);
  if (schema["items"] !== undefined) return new Set(["array"]);
  return null;
}

export function flagKind(schema: JsonSchema, schemas: Record<string, JsonSchema>): FlagKind {
  const resolved = deref(schema, schemas);
  if (isObject(resolved) && resolved["format"] === "binary") return "binary";
  const types = jsonTypes(resolved, schemas);
  if (types === null) return "auto";
  const values = [...types].filter((type) => type !== "null");
  if (values.length === 1 && values[0] === "string") return "string";
  return types.has("string") ? "auto" : "json";
}

function commandsModule(commands: Command[]): string {
  return `${HEADER}// One command per operation of the IR: paridad <resource> <action>, with the literal
// operationId, its flags and the SDK method it calls.
import type { Command } from "./cli.ts";

export const USER_AGENT = ${JSON.stringify(`paridad-ts/${TS_VERSION} cli`)};

export const COMMANDS: readonly Command[] = ${JSON.stringify(commands, null, 2)};
`;
}

