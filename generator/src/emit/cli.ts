// The text a flag takes for a value, or null when the flag cannot give it.
export function flagText(kind: FlagKind, value: unknown): string | null {
  switch (kind) {
    case "string":
      return typeof value === "string" ? value : null;
    case "json":
      return value === undefined ? null : JSON.stringify(value);
    case "auto":
      if (typeof value === "string") return /^[[{]/.test(value) ? null : value;
      return value !== null && typeof value === "object" ? JSON.stringify(value) : null;
    case "binary":
      return null;
  }
}

// Arguments after `paridad` that run an operation with its first example: path and
// query parameters as flags, and the body as flags when each property can be one,
// otherwise as --body.
export function exampleArgv(cmd: Command, op: IROperation): string[] {
  const example = op.examples[0];
  if (example === undefined) throw new Error(`cli: ${op.id} has no example`);
  const argv = [cmd.resource, cmd.action];
  // Path parameters are taken as text.
  for (const flag of cmd.pathParams) argv.push(`--${flag.flag}`, String(example.path[flag.name]));
  for (const flag of cmd.queryParams) {
    if (example.query[flag.name] === undefined) continue;
    const text = flagText(flag.kind, example.query[flag.name]);
    if (text === null) throw new Error(`cli: the example of ${op.id} cannot give --${flag.flag}`);
    argv.push(`--${flag.flag}`, text);
  }
  if (cmd.body !== null) {
    const body = example.body;
    const byName = new Map(cmd.body.flags.map((flag) => [flag.name, flag]));
    const pairs =
      isObject(body) && Object.keys(body).length > 0
        ? Object.entries(body).map(([name, value]) => {
            const flag = byName.get(name);
            const text = flag === undefined ? null : flagText(flag.kind, value);
            return text === null ? null : [`--${flag!.flag}`, text];
          })
        : [null];
    if (pairs.every((pair) => pair !== null)) argv.push(...pairs.flat());
    else argv.push("--body", JSON.stringify(body));
  }
  return argv;
}

function commandsTest(ir: IR, commands: Command[]): string {
  const cases = commands.map((cmd, index) => {
    const op = ir.operations[index]!;
    const example = op.examples[0]!;
    const path = op.path.replace(/\{([^}]+)\}/g, (_, param: string) => encodeURIComponent(String(example.path[param])));
    const multipart = isObject(op.requestBody) && op.requestBody["contentMediaType"] === "multipart/form-data";
    const body = op.requestBody === null || multipart ? "null" : JSON.stringify(JSON.stringify(example.body));
    return `  { id: ${JSON.stringify(op.id)}, argv: ${JSON.stringify(exampleArgv(cmd, op))}, method: ${JSON.stringify(op.method)}, path: ${JSON.stringify(path)}, body: ${body} },`;
  });
  return `${HEADER}// Every command run in process with the first example of its operation: exit code 0,
// JSON on stdout, and the method, path and JSON body of the request the SDK sent.
import assert from "node:assert/strict";
import { createServer } from "node:http";
import type { AddressInfo } from "node:net";
import { after, before, test } from "node:test";
import { run } from "../src/cli.ts";
import { COMMANDS } from "../src/commands.ts";

interface Case {
  id: string;
  argv: string[];
  method: string;
  path: string;
  // JSON body as text, or null when there is no JSON body.
  body: string | null;
}

const cases: Case[] = [
${cases.join("\n")}
];

const received: { method: string; path: string; body: string }[] = [];
const server = createServer((req, res) => {
  const chunks: Buffer[] = [];
  req.on("data", (chunk: Buffer) => chunks.push(chunk));
  req.on("end", () => {
    received.push({ method: req.method ?? "", path: (req.url ?? "").split("?")[0]!, body: Buffer.concat(chunks).toString() });
    res.writeHead(200, { "content-type": "application/json" });
    res.end('{"object":"list","has_more":false,"data":[]}');
  });
});
let baseUrl: string;

before(async () => {
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  baseUrl = \`http://127.0.0.1:\${(server.address() as AddressInfo).port}\`;
});

after(() => new Promise<void>((resolve) => server.close(() => resolve())));

test("there is one command per operation, each with its operationId", () => {
  assert.equal(COMMANDS.length, ${commands.length});
  assert.deepEqual(
    COMMANDS.map((command) => command.operationId),
    cases.map((c) => c.id),
  );
});

for (const c of cases) {
  test(c.id, async () => {
    received.length = 0;
    let stdout = "";
    const code = await run(c.argv, {
      env: { RESEND_API_KEY: "re_paridad_test_9f8e7d6c5b4a39281706", RESEND_BASE_URL: baseUrl },
      isTTY: false,
      stdout: (text) => (stdout += text),
      stderr: () => {},
    });
    assert.equal(code, 0, stdout);
    JSON.parse(stdout);
    assert.equal(received.length, 1);
    const [request] = received;
    assert.equal(request!.method, c.method);
    assert.equal(request!.path, c.path);
    if (c.body !== null) assert.deepEqual(JSON.parse(request!.body), JSON.parse(c.body));
  });
}
`;
}
