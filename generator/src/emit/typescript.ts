// TypeScript SDK emitter (vault/CONTRACT.md §3, §5, §6): writes sdks/typescript from
// the IR. The runtime, tsconfig and runtime tests are static templates in
// generator/templates/typescript/; policy, types, resources, the client and the
// per-operation tests are generated from the IR.
import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type { IR, IROperation, IRParameter } from "../ir.ts";
import { SCHEMAS_REF, isObject, type JsonObject, type JsonSchema } from "../spec.ts";

export const TS_PACKAGE = "paridad-resend";
export const TS_VERSION = "0.0.0-dev";
const TEMPLATES = resolve(import.meta.dirname, "../../templates/typescript");
const HEADER = "// Generated by paridad from ir/ir.json. Do not edit: change ir/overlay.yaml or generator/ and run make generate.\n";
const IDEMPOTENCY_HEADER = "idempotency-key";
// Exported by src/index.ts next to the schema types.
const RESERVED_TYPE_NAMES = new Set(["Resend", "ParidadError", "Result", "ClientOptions", "IdempotentRequestOptions"]);
const RESERVED_PARAMETERS = new Set(["body", "query", "options"]);
const JS_RESERVED = new Set(
  "break case catch class const continue debugger default delete do else enum export extends false finally for function if import in instanceof new null return super switch this throw true try typeof var void while with yield let static implements interface package private protected public await".split(
    " ",
  ),
);

type Ref = (name: string) => string;

export function emitTypescript(ir: IR, outDir: string): void {
  const root = join(outDir, "sdks/typescript");
  // node_modules (pnpm) survives; everything the emitter owns is rewritten.
  for (const owned of ["src", "test", "package.json", "tsconfig.json"]) rmSync(join(root, owned), { recursive: true, force: true });
  mkdirSync(join(root, "src"), { recursive: true });
  mkdirSync(join(root, "test"), { recursive: true });
  cpSync(join(TEMPLATES, "tsconfig.json"), join(root, "tsconfig.json"));
  cpSync(join(TEMPLATES, "src/runtime.ts"), join(root, "src/runtime.ts"));
  cpSync(join(TEMPLATES, "test/runtime.test.ts"), join(root, "test/runtime.test.ts"));
  writeFileSync(join(root, "package.json"), packageJson());
  writeFileSync(join(root, "src/policy.ts"), policyModule(ir));
  writeFileSync(join(root, "src/types.ts"), typesModule(ir));
  const resources = groupResources(ir.operations);
  for (const resource of resources) {
    if (resource.className in ir.schemas) throw new Error(`typescript: schema name ${resource.className} collides with the class of resource ${resource.property}`);
  }
  writeFileSync(join(root, "src/resources.ts"), resourcesModule(resources));
  writeFileSync(join(root, "src/index.ts"), indexModule(resources));
  writeFileSync(join(root, "test/operations.test.ts"), operationsTest(resources));
}

function packageJson(): string {
  const manifest = {
    name: TS_PACKAGE,
    version: TS_VERSION,
    description: "Resend API client generated by paridad from the pinned OpenAPI specification.",
    license: "MIT",
    type: "module",
    exports: { ".": "./src/index.ts" },
    files: ["src"],
    engines: { node: ">=26" },
    scripts: { check: "tsc --strict --noEmit -p .", test: "node --test" },
    peerDependencies: { "@react-email/render": "^2.3.1" },
    peerDependenciesMeta: { "@react-email/render": { optional: true } },
    devDependencies: { "@types/node": "26.6.6", typescript: "7.0.2" },
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

function policyModule(ir: IR): string {
  return `${HEADER}// policy of the IR (vault/CONTRACT.md §5.3).
import type { Policy } from "./runtime.ts";

export const VERSION = ${JSON.stringify(TS_VERSION)};

export const POLICY: Policy = ${JSON.stringify(ir.policy, null, 2)};
`;
}

// ---------------------------------------------------------------- schema types

function typesModule(ir: IR): string {
  const names = Object.keys(ir.schemas).sort();
  const blocks = names.map((name) => {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error(`typescript: schema name ${name} is not an identifier`);
    if (RESERVED_TYPE_NAMES.has(name)) throw new Error(`typescript: schema name ${name} collides with an export of the SDK`);
    const schema = ir.schemas[name]!;
    return `${docComment(isObject(schema) ? schemaDoc(schema) : [], "")}export type ${name} = ${tsType(schema, (ref) => ref, "")};\n`;
  });
  return `${HEADER}// Schemas of the specification (components.schemas), as TypeScript types.\n\n${blocks.join("\n")}`;
}

// JSON Schema 2020-12 to a TypeScript type. `ref` names a component schema.
export function tsType(schema: JsonSchema, ref: Ref, indent: string): string {
  if (schema === true) return "unknown";
  if (schema === false) return "never";
  if (typeof schema["$ref"] === "string") {
    if (!schema["$ref"].startsWith(SCHEMAS_REF)) throw new Error(`typescript: $ref ${schema["$ref"]} is not a component schema`);
    return ref(schema["$ref"].slice(SCHEMAS_REF.length));
  }
  if ("const" in schema) return literal(schema["const"]);
  if (Array.isArray(schema["enum"])) return union([...new Set(schema["enum"].map(literal))]);
  const parts: string[] = [];
  const own = ownType(schema, ref, indent);
  if (own !== null) parts.push(own);
  if (Array.isArray(schema["allOf"])) for (const member of schema["allOf"] as JsonSchema[]) parts.push(tsType(member, ref, indent));
  for (const key of ["oneOf", "anyOf"]) {
    if (Array.isArray(schema[key])) parts.push(union((schema[key] as JsonSchema[]).map((branch) => tsType(branch, ref, indent))));
  }
  if (parts.length === 0) return "unknown";
  return parts.length === 1 ? parts[0]! : parts.map((part) => (part.includes(" | ") ? `(${part})` : part)).join(" & ");
}

function ownType(schema: JsonObject, ref: Ref, indent: string): string | null {
  let types: string[];
  if (typeof schema["type"] === "string") types = [schema["type"]];
  else if (Array.isArray(schema["type"])) types = schema["type"].filter((type: unknown): type is string => typeof type === "string");
  else if (schema["properties"] !== undefined || schema["additionalProperties"] !== undefined) types = ["object"];
  else if (schema["items"] !== undefined) types = ["array"];
  else return null;
  return union(
    types.map((type) => {
      switch (type) {
        case "string":
          return schema["format"] === "binary" ? "Blob" : "string";
        case "integer":
        case "number":
          return "number";
        case "boolean":
          return "boolean";
        case "null":
          return "null";
        case "array": {
          const items = (schema["items"] as JsonSchema | undefined) ?? true;
          return `Array<${tsType(items, ref, indent)}>`;
        }
        case "object":
          return objectType(schema, ref, indent);
        default:
          return "unknown";
      }
    }),
  );
}

function objectType(schema: JsonObject, ref: Ref, indent: string): string {
  const properties = isObject(schema["properties"]) ? schema["properties"] : {};
  const required = new Set(Array.isArray(schema["required"]) ? schema["required"] : []);
  const additional = schema["additionalProperties"];
  const inner = `${indent}  `;
  const lines: string[] = [];
  for (const [name, property] of Object.entries(properties)) {
    const doc = isObject(property) ? schemaDoc(property) : [];
    lines.push(`${docComment(doc, inner)}${inner}${propertyKey(name)}${required.has(name) ? "" : "?"}: ${tsType(property as JsonSchema, ref, inner)};`);
  }
  if (Object.keys(properties).length === 0 && additional !== false) {
    const value = isObject(additional) ? tsType(additional, ref, inner) : "unknown";
    lines.push(`${inner}[key: string]: ${value};`);
  } else if (isObject(additional)) {
    lines.push(`${inner}[key: string]: unknown;`);
  }
  return lines.length === 0 ? "{}" : `{\n${lines.join("\n")}\n${indent}}`;
}

function union(members: string[]): string {
  if (members.length === 0) return "never";
  return members.map((member) => (member.includes(" & ") ? `(${member})` : member)).join(" | ");
}

function literal(value: unknown): string {
  if (value === null || typeof value === "string" || typeof value === "number" || typeof value === "boolean") return JSON.stringify(value);
  return "unknown";
}

function propertyKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function schemaDoc(schema: JsonObject): string[] {
  const lines = typeof schema["description"] === "string" ? schema["description"].trim().split("\n") : [];
  if (schema["deprecated"] === true) lines.push("@deprecated");
  return lines;
}

function docComment(lines: string[], indent: string): string {
  if (lines.length === 0) return "";
  const safe = lines.map((line) => line.replaceAll("*/", "*\\/").trimEnd());
  return `${indent}/**\n${safe.map((line) => `${indent} *${line === "" ? "" : ` ${line}`}`).join("\n")}\n${indent} */\n`;
}

// ------------------------------------------------------------------- resources

interface Method {
  op: IROperation;
  name: string;
  // Identifier of each path parameter, in template order.
  pathArgs: string[];
}

interface Resource {
  property: string;
  className: string;
  methods: Method[];
}

function groupResources(operations: IROperation[]): Resource[] {
  const resources = new Map<string, Resource>();
  for (const op of operations) {
    const parts = op.names.ts.split(".");
    if (parts.length !== 2 || !parts.every((part) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(part))) {
      throw new Error(`typescript: names.ts ${op.names.ts} of ${op.id} is not resource.method`);
    }
    const [property, name] = parts as [string, string];
    for (const parameter of op.headerParams) {
      if (parameter.name.toLowerCase() !== IDEMPOTENCY_HEADER) throw new Error(`typescript: header ${parameter.name} of ${op.id} is not supported`);
    }
    for (const parameter of op.queryParams) {
      if (parameter.style !== "form") throw new Error(`typescript: query parameter ${parameter.name} of ${op.id} has style ${parameter.style}`);
    }
    const pathArgs = op.pathParams.map((parameter) => identifier(parameter.name));
    if (new Set(pathArgs).size !== pathArgs.length || pathArgs.some((arg) => RESERVED_PARAMETERS.has(arg))) {
      throw new Error(`typescript: path parameters of ${op.id} give clashing argument names ${pathArgs.join(", ")}`);
    }
    let resource = resources.get(property);
    if (resource === undefined) {
      resource = { property, className: property.charAt(0).toUpperCase() + property.slice(1), methods: [] };
      resources.set(property, resource);
    }
    resource.methods.push({ op, name, pathArgs });
  }
  for (const resource of resources.values()) {
    const taken = new Set<string>();
    for (const method of resource.methods) {
      for (const name of method.op.pagination === null ? [method.name] : [method.name, `${method.name}All`]) {
        if (taken.has(name)) throw new Error(`typescript: method ${resource.property}.${name} is generated twice`);
        taken.add(name);
      }
    }
  }
  return [...resources.values()].sort((a, b) => (a.property < b.property ? -1 : a.property > b.property ? 1 : 0));
}

function identifier(name: string): string {
  const words = name.split(/[^A-Za-z0-9]+/).filter((word) => word !== "");
  let value = words.map((word, index) => (index === 0 ? word.charAt(0).toLowerCase() + word.slice(1) : word.charAt(0).toUpperCase() + word.slice(1))).join("");
  if (value === "" || /^[0-9]/.test(value)) value = `p${value}`;
  return JS_RESERVED.has(value) ? `${value}Value` : value;
}

const typeRef: Ref = (name) => `T.${name}`;

function opConst(op: IROperation): string {
  return `op_${op.id.replace(/[^A-Za-z0-9]/g, "_")}`;
}

function bodyKind(op: IROperation): "json" | "multipart" | null {
  if (op.requestBody === null) return null;
  const media = isObject(op.requestBody) ? op.requestBody["contentMediaType"] : undefined;
  if (media === undefined) return "json";
  if (media === "multipart/form-data") return "multipart";
  throw new Error(`typescript: request body ${String(media)} of ${op.id} is not supported`);
}

function queryType(parameters: IRParameter[], indent: string): string {
  const inner = `${indent}  `;
  const lines = parameters.map(
    (parameter) =>
      `${docComment(parameter.description === null ? [] : parameter.description.trim().split("\n"), inner)}${inner}${propertyKey(parameter.name)}${parameter.required ? "" : "?"}: ${tsType(parameter.schema, typeRef, inner)};`,
  );
  return `{\n${lines.join("\n")}\n${indent}}`;
}

function bodyType(op: IROperation, indent: string): string {
  const schema = op.requestBody!;
  // The media type annotation is not part of the value.
  const value = isObject(schema) && "contentMediaType" in schema ? Object.fromEntries(Object.entries(schema).filter(([key]) => key !== "contentMediaType")) : schema;
  const type = tsType(value, typeRef, indent);
  return op.id === "emails/send" ? `${type.includes(" | ") ? `(${type})` : type} & {\n${indent}  /** A React Email element, rendered to \`html\` with @react-email/render before sending. */\n${indent}  react?: unknown;\n${indent}}` : type;
}

function responseType(op: IROperation, indent: string): string {
  return op.response.schema === null ? "null" : tsType(op.response.schema, typeRef, indent);
}

function operationLiteral(op: IROperation): string {
  const query = op.queryParams.map((parameter) => `{ name: ${JSON.stringify(parameter.name)}, explode: ${parameter.explode} }`);
  const fields = [
    `id: ${JSON.stringify(op.id)}`,
    `method: ${JSON.stringify(op.method)}`,
    `path: ${JSON.stringify(op.path)}`,
    `query: [${query.join(", ")}]`,
    `body: ${JSON.stringify(bodyKind(op))}`,
  ];
  if (op.id === "emails/send") fields.push("react: true");
  return `const ${opConst(op)}: Operation = { ${fields.join(", ")} };`;
}

function methodSource(method: Method): string {
  const { op } = method;
  const indent = "  ";
  const params = op.pathParams.map((parameter, index) => `${method.pathArgs[index]}: ${tsType(parameter.schema, typeRef, indent)}`);
  if (op.requestBody !== null) params.push(`body: ${bodyType(op, indent)}`);
  const hasQuery = op.queryParams.length > 0;
  const queryRequired = op.queryParams.some((parameter) => parameter.required);
  if (hasQuery) params.push(`query${queryRequired ? "" : "?"}: ${queryType(op.queryParams, indent)}`);
  if (op.idempotency) params.push("options?: IdempotentRequestOptions");
  const path = `[${method.pathArgs.join(", ")}]`;
  const call = `this.#core.request(${opConst(op)}, ${path}, ${hasQuery ? "query" : "undefined"}, ${op.requestBody !== null ? "body" : "undefined"}${op.idempotency ? ", options" : ""})`;
  const doc = [...(op.summary === null ? [] : [op.summary, ""]), `operationId: \`${op.id}\` — \`${op.method} ${op.path}\``];
  let source = `${docComment(doc, indent)}${indent}${method.name}(${params.join(", ")}): Promise<Result<${responseType(op, indent)}>> {\n${indent}  return ${call};\n${indent}}\n`;

  if (op.pagination !== null) {
    const pageQuery = op.queryParams.filter((parameter) => parameter.name !== op.pagination!.after && parameter.name !== op.pagination!.before);
    const allParams = op.pathParams.map((parameter, index) => `${method.pathArgs[index]}: ${tsType(parameter.schema, typeRef, indent)}`);
    if (pageQuery.length > 0) allParams.push(`query${pageQuery.some((parameter) => parameter.required) ? "" : "?"}: ${queryType(pageQuery, indent)}`);
    const item = `NonNullable<(${responseType(op, indent)})[${JSON.stringify(op.pagination.items)}]>[number]`;
    const allDoc = [
      `Every item of every page of \`${op.id}\`, following \`${op.pagination.after}\` while \`${op.pagination.hasMore}\` is true. Throws ParidadError on a failed page.`,
      "",
      `operationId: \`${op.id}\` — \`${op.method} ${op.path}\``,
    ];
    source += `\n${docComment(allDoc, indent)}${indent}${method.name}All(${allParams.join(", ")}): AsyncGenerator<${item}, void, undefined> {\n${indent}  return this.#core.paginate(${opConst(op)}, ${path}, ${pageQuery.length > 0 ? "query" : "undefined"});\n${indent}}\n`;
  }
  return source;
}

function resourcesModule(resources: Resource[]): string {
  const constants = resources.flatMap((resource) => resource.methods.map((method) => operationLiteral(method.op)));
  const classes = resources.map(
    (resource) => `export class ${resource.className} {
  readonly #core: Core;

  constructor(core: Core) {
    this.#core = core;
  }

${resource.methods.map(methodSource).join("\n")}}
`,
  );
  return `${HEADER}// One method per operation of the IR; paginated operations also get <method>All.
import type { Core, IdempotentRequestOptions, Operation, Result } from "./runtime.ts";
import type * as T from "./types.ts";

${constants.join("\n")}

${classes.join("\n")}`;
}

function indexModule(resources: Resource[]): string {
  const fields = resources.map((resource) => `  readonly ${resource.property}: ${resource.className};`);
  const assignments = resources.map((resource) => `    this.${resource.property} = new ${resource.className}(core);`);
  return `${HEADER}import { Core, type ClientOptions } from "./runtime.ts";
import { ${resources.map((resource) => resource.className).join(", ")} } from "./resources.ts";

export { ParidadError, type ClientOptions, type IdempotentRequestOptions, type Result } from "./runtime.ts";
// The resource classes are exported as types so that their methods are part of the
// API report of api-extractor (C19); only Resend builds them.
export type { ${resources.map((resource) => resource.className).join(", ")} };
export type * from "./types.ts";

// new Resend(key?, options?): the key defaults to RESEND_API_KEY (vault/CONTRACT.md §5.1).
export class Resend {
${fields.join("\n")}

  constructor(apiKey?: string, options?: ClientOptions) {
    const core = new Core(apiKey, options);
${assignments.join("\n")}
  }
}
`;
}

// ------------------------------------------------------------------------ tests

function operationsTest(resources: Resource[]): string {
  const cases = resources.flatMap((resource) =>
    resource.methods.map(({ op, name }) => {
      const example = op.examples[0];
      if (example === undefined) throw new Error(`typescript: ${op.id} has no example`);
      const args = op.pathParams.map((parameter) => String(example.path[parameter.name]));
      const path = op.path.replace(/\{([^}]+)\}/g, (_, param: string) => encodeURIComponent(String(example.path[param])));
      const callArgs = args.map((arg) => `${JSON.stringify(arg)} as never`);
      if (op.requestBody !== null) callArgs.push(`${JSON.stringify(example.body)} as never`);
      if (op.queryParams.length > 0) callArgs.push(`${JSON.stringify(example.query)} as never`);
      const body = bodyKind(op) === "json" ? JSON.stringify(JSON.stringify(example.body)) : "null";
      return `  { id: ${JSON.stringify(op.id)}, method: ${JSON.stringify(op.method)}, path: ${JSON.stringify(path)}, body: ${body}, call: (r) => r.${resource.property}.${name}(${callArgs.join(", ")}) },`;
    }),
  );
  return `${HEADER}// One request per operation of the IR with its first example: method, path and JSON body as sent.
import assert from "node:assert/strict";
import { createServer } from "node:http";
import type { AddressInfo } from "node:net";
import { after, before, test } from "node:test";
import { Resend, type Result } from "../src/index.ts";

interface Case {
  id: string;
  method: string;
  path: string;
  // JSON body as text, or null when there is no JSON body.
  body: string | null;
  call: (resend: Resend) => Promise<Result<unknown>>;
}

const cases: Case[] = [
${cases.join("\n")}
];

const received: { method: string; path: string; body: string }[] = [];
const server = createServer((req, res) => {
  const chunks: Buffer[] = [];
  req.on("data", (chunk: Buffer) => chunks.push(chunk));
  req.on("end", () => {
    received.push({ method: req.method ?? "", path: (req.url ?? "").split("?")[0]!, body: Buffer.concat(chunks).toString() });
    res.writeHead(200, { "content-type": "application/json" });
    res.end("{}");
  });
});
let resend: Resend;

before(async () => {
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  resend = new Resend("re_paridad_test_9f8e7d6c5b4a39281706", { baseUrl: \`http://127.0.0.1:\${(server.address() as AddressInfo).port}\` });
});

after(() => new Promise<void>((resolve) => server.close(() => resolve())));

test("there is one case per operation", () => {
  assert.equal(new Set(cases.map((c) => c.id)).size, ${resources.reduce((count, resource) => count + resource.methods.length, 0)});
});

for (const c of cases) {
  test(c.id, async () => {
    received.length = 0;
    const { error } = await c.call(resend);
    assert.equal(error, null);
    assert.equal(received.length, 1);
    const [request] = received;
    assert.equal(request!.method, c.method);
    assert.equal(request!.path, c.path);
    if (c.body !== null) assert.deepEqual(JSON.parse(request!.body), JSON.parse(c.body));
  });
}
`;
}
