// Go SDK emitter (vault/CONTRACT.md §3, §5, §6): writes sdks/go from the IR. The
// runtime and runtime tests are static templates in generator/templates/go/;
// go.mod, the policy, the schema types, the services, the client and the
// per-operation tests are generated from the IR. The emitter runs gofmt on the
// output, so the committed tree is formatted.
import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type { IR, IROperation, IRParameter } from "../ir.ts";
import { SCHEMAS_REF, isObject, type JsonObject, type JsonSchema } from "../spec.ts";

export const GO_VERSION = "0.0.0-dev";
export const GO_LANGUAGE = "1.23";
const TEMPLATES = resolve(import.meta.dirname, "../../templates/go");
const HEADER = "// Code generated by paridad from ir/ir.json. DO NOT EDIT: change ir/overlay.yaml or generator/ and run make generate.\n\n";
const IDEMPOTENCY_HEADER = "idempotency-key";
// Exported by the runtime template next to the generated names.
const RESERVED_TYPE_NAMES = new Set(["Client", "Error", "Option", "RequestOption", "Version", "UserAgent", "NewClient", "Ptr", "WithAPIKey", "WithBaseURL", "WithTimeout", "WithIdempotencyKey"]);
// Go keywords, predeclared identifiers and the names a generated method already uses.
const RESERVED_IDENTIFIERS = new Set(
  "break case chan const continue default defer else fallthrough for func go goto if import interface map package range return select struct switch type var any bool byte error false float64 int int64 iota len make new nil rune string true ctx body query options s".split(" "),
);
// Initialisms written in capitals, as Go names them.
const INITIALISMS = new Set(["api", "css", "dns", "html", "http", "https", "id", "ip", "json", "smtp", "sql", "tls", "ttl", "ui", "uid", "uri", "url", "uuid", "xml"]);
// Keywords of a schema that only constrain a value and do not give it a shape.
const SHAPE_KEYWORDS = ["type", "properties", "additionalProperties", "items", "$ref", "allOf", "oneOf", "anyOf", "enum", "const"];

export function emitGo(ir: IR, outDir: string): void {
  const root = join(outDir, "sdks/go");
  rmSync(root, { recursive: true, force: true });
  mkdirSync(root, { recursive: true });
  cpSync(join(TEMPLATES, "runtime.go"), join(root, "runtime.go"));
  cpSync(join(TEMPLATES, "runtime_test.go"), join(root, "runtime_test.go"));
  writeFileSync(join(root, "go.mod"), `module ${ir.project.go_module}\n\ngo ${GO_LANGUAGE}\n`);
  writeFileSync(join(root, "policy.go"), policyFile(ir));
  const types = new GoTypes(ir.schemas);
  const services = groupServices(ir.operations);
  // Services first: their query, body and response types land in types.go too.
  const servicesSource = servicesFile(services, types);
  writeFileSync(join(root, "services.go"), servicesSource);
  writeFileSync(join(root, "types.go"), types.file());
  writeFileSync(join(root, "client.go"), clientFile(services));
  writeFileSync(join(root, "operations_test.go"), operationsTest(services, types));
  execFileSync("gofmt", ["-w", root], { stdio: ["ignore", "ignore", "inherit"] });
}

// ----------------------------------------------------------------------- policy

interface RetryRules {
  // A rule without `name` matches any name; `name: null` matches a body without `name`.
  responses: { status: number; name?: string | null }[];
  transport: string[];
}

// `policy` of the IR (ir/overlay.yaml).
interface Policy {
  max_attempts: number;
  safe_methods: string[];
  safe_with_idempotency_key: boolean;
  retry_always: RetryRules;
  retry_if_safe: RetryRules;
  backoff: { retry_after_jitter_ms: number; retry_after_max_seconds: number; base_ms: number; cap_ms: number };
  idempotency_key: { header: string; min_length: number; max_length: number; error_code: string; error_message: string };
}

function policyFile(ir: IR): string {
  const policy = ir.policy as unknown as Policy;
  const strings = (values: string[]) => `[]string{${values.map((value) => JSON.stringify(value)).join(", ")}}`;
  const rules = (value: RetryRules) => {
    const responses = value.responses.map((rule) => {
      if (!("name" in rule)) return `{status: ${rule.status}, anyName: true}`;
      return rule.name === null ? `{status: ${rule.status}}` : `{status: ${rule.status}, name: ptr(${JSON.stringify(rule.name)})}`;
    });
    return `retryRules{\n\t\tresponses: []responseRule{${responses.join(", ")}},\n\t\ttransport: ${strings(value.transport)},\n\t}`;
  };
  const { backoff, idempotency_key: key } = policy;
  return `${HEADER}// policy of the IR (vault/CONTRACT.md §5.3).

package resend

// Version of the SDK; the release service writes the published one in its build copy.
const Version = ${JSON.stringify(GO_VERSION)}

var currentPolicy = policy{
	maxAttempts: ${policy.max_attempts},
	safeMethods: ${strings(policy.safe_methods)},
	safeWithIdempotencyKey: ${policy.safe_with_idempotency_key},
	retryAlways: ${rules(policy.retry_always)},
	retryIfSafe: ${rules(policy.retry_if_safe)},
	backoff: backoffPolicy{retryAfterJitterMS: ${backoff.retry_after_jitter_ms}, retryAfterMaxSeconds: ${backoff.retry_after_max_seconds}, baseMS: ${backoff.base_ms}, capMS: ${backoff.cap_ms}},
	idempotencyKey: idempotencyKeyPolicy{
		header: ${JSON.stringify(key.header)},
		minLength: ${key.min_length},
		maxLength: ${key.max_length},
		errorCode: ${JSON.stringify(key.error_code)},
		errorMessage: ${JSON.stringify(key.error_message)},
	},
}
`;
}

// ------------------------------------------------------------------ schema types

// Go type of a schema: the expression, what kind of value it is (decides pointers
// and omitempty), whether the schema admits null, and the named struct behind it.
export interface GoType {
  expr: string;
  kind: "struct" | "slice" | "map" | "any" | "scalar";
  nullable: boolean;
  struct: string | null;
}

interface Field {
  name: string;
  json: string;
  type: GoType;
  required: boolean;
  doc: string[];
}

interface StructDef {
  name: string;
  doc: string[];
  fields: Field[];
  source: JsonSchema;
}

type Shape = Map<string, { schema: JsonSchema; required: boolean }>;

const ANY: GoType = { expr: "any", kind: "any", nullable: false, struct: null };

export class GoTypes {
  readonly #schemas: Record<string, JsonSchema>;
  readonly #structs = new Map<string, StructDef>();
  readonly #aliases = new Map<string, { doc: string[]; expr: string }>();
  readonly #components = new Map<string, GoType>();
  readonly #inProgress = new Set<string>();
  readonly #shaping = new Set<string>();
  readonly #extra: string[] = [];

  constructor(schemas: Record<string, JsonSchema>) {
    this.#schemas = schemas;
    for (const name of Object.keys(schemas).sort()) this.component(name);
  }

  // Go type of the component schema `name`, defined once in types.go.
  component(name: string): GoType {
    const known = this.#components.get(name);
    if (known !== undefined) return known;
    const goName = exportedName(name);
    if (this.#inProgress.has(name)) return { expr: goName, kind: "any", nullable: false, struct: null };
    const schema = this.#schemas[name];
    if (schema === undefined) throw new Error(`go: schema ${name} does not exist`);
    this.#inProgress.add(name);
    const doc = isObject(schema) ? schemaDoc(schema) : [];
    let type: GoType;
    if (this.shape(schema) !== null) {
      type = { expr: goName, kind: "struct", nullable: false, struct: goName };
      this.#components.set(name, type);
      this.#struct(goName, schema, doc);
    } else {
      const inner = this.resolve(schema, `${goName}Value`);
      this.#claim(goName, schema);
      this.#aliases.set(goName, { doc, expr: inner.expr });
      type = { ...inner, expr: goName };
      this.#components.set(name, type);
    }
    this.#inProgress.delete(name);
    return type;
  }

  // Go type of a schema; inline objects become structs named `hint`.
  resolve(schema: JsonSchema, hint: string): GoType {
    if (!isObject(schema)) return ANY;
    if (typeof schema["$ref"] === "string") {
      if (!schema["$ref"].startsWith(SCHEMAS_REF)) throw new Error(`go: $ref ${schema["$ref"]} is not a component schema`);
      return this.component(schema["$ref"].slice(SCHEMAS_REF.length));
    }
    const nullable = isNullable(schema);
    if ("const" in schema) return scalarOf([schema["const"]], nullable);
    if (Array.isArray(schema["enum"])) return scalarOf(schema["enum"], nullable);
    const types = typeList(schema).filter((type) => type !== "null");
    if (types.length === 0 && Array.isArray(schema["allOf"]) && schema["oneOf"] === undefined && schema["anyOf"] === undefined) {
      const members = (schema["allOf"] as JsonSchema[]).filter((member) => !constraintOnly(member));
      if (members.length === 1 && schema["properties"] === undefined) return { ...this.resolve(members[0]!, hint), nullable };
    }
    if (this.shape(schema) !== null) {
      this.#struct(hint, schema, isObject(schema) ? schemaDoc(schema) : []);
      return { expr: hint, kind: "struct", nullable, struct: hint };
    }
    if (types.length !== 1) return { ...ANY, nullable };
    switch (types[0]) {
      case "string":
        return schema["format"] === "binary" ? { expr: "[]byte", kind: "slice", nullable, struct: null } : { expr: "string", kind: "scalar", nullable, struct: null };
      case "integer":
        return { expr: "int", kind: "scalar", nullable, struct: null };
      case "number":
        return { expr: "float64", kind: "scalar", nullable, struct: null };
      case "boolean":
        return { expr: "bool", kind: "scalar", nullable, struct: null };
      case "array":
        return { expr: `[]${element(this.resolve((schema["items"] as JsonSchema | undefined) ?? true, `${hint}Item`))}`, kind: "slice", nullable, struct: null };
      case "object": {
        const additional = schema["additionalProperties"];
        const value = isObject(additional) ? element(this.resolve(additional, `${hint}Value`)) : "any";
        return { expr: `map[string]${value}`, kind: "map", nullable, struct: null };
      }
      default:
        return { ...ANY, nullable };
    }
  }

  // Properties of a schema that is always an object: its own, those of allOf and,
  // as optional, those of oneOf/anyOf branches. null when it can be something else.
  shape(schema: JsonSchema): Shape | null {
    if (!isObject(schema)) return null;
    if (typeof schema["$ref"] === "string") {
      const name = schema["$ref"].slice(SCHEMAS_REF.length);
      const target = this.#schemas[name];
      if (target === undefined || this.#shaping.has(name)) return null;
      this.#shaping.add(name);
      try {
        return this.shape(target);
      } finally {
        this.#shaping.delete(name);
      }
    }
    if ("const" in schema || schema["enum"] !== undefined) return null;
    const types = typeList(schema).filter((type) => type !== "null");
    if (types.some((type) => type !== "object")) return null;
    const shape: Shape = new Map();
    const merge = (other: Shape, optional: boolean) => {
      for (const [name, property] of other) {
        const known = shape.get(name);
        if (known === undefined) shape.set(name, { schema: property.schema, required: property.required && !optional });
        else if (property.required && !optional) known.required = true;
      }
    };
    if (isObject(schema["properties"])) {
      for (const [name, property] of Object.entries(schema["properties"])) shape.set(name, { schema: property as JsonSchema, required: false });
    }
    if (Array.isArray(schema["allOf"])) {
      for (const member of schema["allOf"] as JsonSchema[]) {
        if (constraintOnly(member)) continue;
        const other = this.shape(member);
        if (other === null) return null;
        merge(other, false);
      }
    }
    for (const key of ["oneOf", "anyOf"]) {
      if (!Array.isArray(schema[key])) continue;
      for (const branch of schema[key] as JsonSchema[]) {
        if (constraintOnly(branch)) continue;
        const other = this.shape(branch);
        if (other === null) return null;
        merge(other, true);
      }
    }
    for (const name of Array.isArray(schema["required"]) ? schema["required"] : []) {
      const known = shape.get(String(name));
      if (known !== undefined) known.required = true;
    }
    return shape.size === 0 ? null : shape;
  }

  // A struct for a query of an operation, with json tags so examples decode into it.
  query(name: string, parameters: IRParameter[]): void {
    this.#claim(name, parameters);
    const fields = parameters.map((parameter) => {
      const type = this.resolve(parameter.schema, `${name}${fieldName(parameter.name)}`);
      if (type.kind !== "scalar" && !(type.kind === "slice" && type.expr !== "[]byte")) {
        throw new Error(`go: query parameter ${parameter.name} of ${name} has type ${type.expr}`);
      }
      return { name: fieldName(parameter.name), json: parameter.name, type, required: parameter.required, doc: parameter.description === null ? [] : parameter.description.trim().split("\n") };
    });
    checkFieldNames(name, fields);
    this.#structs.set(name, { name, doc: [], fields, source: true });
  }

  // Extra source appended to types.go (the values() methods of the queries).
  append(source: string): void {
    this.#extra.push(source);
  }

  file(): string {
    const pointers = this.#pointerEdges();
    const blocks: string[] = [];
    const names = [...new Set([...this.#structs.keys(), ...this.#aliases.keys()])].sort();
    for (const name of names) {
      const alias = this.#aliases.get(name);
      if (alias !== undefined) {
        blocks.push(`${comment(alias.doc, "")}type ${name} = ${alias.expr}\n`);
        continue;
      }
      const def = this.#structs.get(name)!;
      const lines = def.fields.map((field) => {
        const { expr, omit } = fieldType(field, pointers.has(`${def.name}.${field.name}`));
        return `${comment(field.doc, "\t")}\t${field.name} ${expr} \`json:"${field.json}${omit ? ",omitempty" : ""}"\``;
      });
      blocks.push(`${comment(def.doc, "")}type ${name} struct {\n${lines.join("\n")}\n}\n`);
    }
    return `${HEADER}// Schemas of the specification (components.schemas) and the queries of the
// operations, as Go types. Optional fields are pointers (slices, maps and any are
// nil when absent) and are left out of the JSON when unset.

package resend

${blocks.join("\n")}${this.#extra.length === 0 ? "" : `\n${this.#extra.join("\n")}`}`;
  }

  #struct(name: string, schema: JsonSchema, doc: string[]): void {
    const known = this.#structs.get(name);
    if (known !== undefined && known.source === schema) return;
    this.#claim(name, schema);
    const def: StructDef = { name, doc, fields: [], source: schema };
    this.#structs.set(name, def);
    for (const [json, property] of this.shape(schema)!) {
      if (!/^[A-Za-z0-9_!#$%&()*+\-./:;<=>?@[\]^{|}~ ]+$/.test(json)) throw new Error(`go: property ${json} of ${name} cannot be a json tag`);
      const goName = fieldName(json);
      def.fields.push({ name: goName, json, type: this.resolve(property.schema, `${name}${goName}`), required: property.required, doc: isObject(property.schema) ? schemaDoc(property.schema) : [] });
    }
    checkFieldNames(name, def.fields);
  }

  #claim(name: string, source: unknown): void {
    if (!/^[A-Z][A-Za-z0-9_]*$/.test(name)) throw new Error(`go: type name ${name} is not an exported identifier`);
    if (RESERVED_TYPE_NAMES.has(name)) throw new Error(`go: type name ${name} collides with the runtime`);
    const known = this.#structs.get(name);
    if ((known !== undefined && known.source !== source) || this.#aliases.has(name)) throw new Error(`go: type name ${name} is generated twice`);
  }

  // Required struct fields are values unless they close a cycle of values, which Go
  // cannot lay out; those fields become pointers.
  #pointerEdges(): Set<string> {
    const edges = new Map<string, { field: string; target: string }[]>();
    for (const def of this.#structs.values()) {
      edges.set(
        def.name,
        def.fields.filter((field) => fieldType(field, false).value !== null).map((field) => ({ field: field.name, target: fieldType(field, false).value! })),
      );
    }
    const reaches = (from: string, to: string, seen: Set<string>): boolean => {
      if (from === to) return true;
      if (seen.has(from)) return false;
      seen.add(from);
      return (edges.get(from) ?? []).some((edge) => reaches(edge.target, to, seen));
    };
    const pointers = new Set<string>();
    for (const [name, list] of edges) for (const edge of list) if (reaches(edge.target, name, new Set())) pointers.add(`${name}.${edge.field}`);
    return pointers;
  }
}

// How a field is written: pointer for optional or nullable scalars and structs.
// `value` is the struct held by value, for the cycle check.
function fieldType(field: Field, forcePointer: boolean): { expr: string; omit: boolean; value: string | null } {
  const { type, required } = field;
  const pointable = type.kind === "scalar" || type.kind === "struct";
  const pointer = pointable && (!required || type.nullable || forcePointer);
  return { expr: pointer ? `*${type.expr}` : type.expr, omit: !required, value: !pointer && type.kind === "struct" ? type.struct : null };
}

function element(type: GoType): string {
  return type.nullable && (type.kind === "scalar" || type.kind === "struct") ? `*${type.expr}` : type.expr;
}

function scalarOf(values: unknown[], nullable: boolean): GoType {
  const present = values.filter((value) => value !== null);
  const all = (test: (value: unknown) => boolean) => present.length > 0 && present.every(test);
  const scalar = (expr: string): GoType => ({ expr, kind: "scalar", nullable: nullable || present.length < values.length, struct: null });
  if (all((value) => typeof value === "string")) return scalar("string");
  if (all((value) => Number.isInteger(value))) return scalar("int");
  if (all((value) => typeof value === "number")) return scalar("float64");
  if (all((value) => typeof value === "boolean")) return scalar("bool");
  return { ...ANY, nullable };
}

function typeList(schema: JsonObject): string[] {
  if (typeof schema["type"] === "string") return [schema["type"]];
  if (Array.isArray(schema["type"])) return schema["type"].filter((type: unknown): type is string => typeof type === "string");
  if (schema["properties"] !== undefined || schema["additionalProperties"] !== undefined) return ["object"];
  if (schema["items"] !== undefined) return ["array"];
  return [];
}

function isNullable(schema: JsonObject): boolean {
  return typeList(schema).includes("null") || (Array.isArray(schema["enum"]) && schema["enum"].includes(null)) || schema["const"] === null;
}

function constraintOnly(schema: JsonSchema): boolean {
  return isObject(schema) && SHAPE_KEYWORDS.every((key) => !(key in schema));
}

function checkFieldNames(owner: string, fields: Field[]): void {
  const seen = new Set<string>();
  for (const field of fields) {
    if (seen.has(field.name)) throw new Error(`go: field ${field.name} of ${owner} is generated twice`);
    seen.add(field.name);
  }
}

function schemaDoc(schema: JsonObject): string[] {
  const lines = typeof schema["description"] === "string" ? schema["description"].trim().split("\n") : [];
  if (schema["deprecated"] === true) lines.push(...(lines.length === 0 ? [] : [""]), "Deprecated: deprecated in the specification.");
  return lines;
}

function comment(lines: string[], indent: string): string {
  return lines.map((line) => `${indent}//${line.trimEnd() === "" ? "" : ` ${line.trimEnd()}`}\n`).join("");
}

function words(name: string): string[] {
  return name
    .split(/[^A-Za-z0-9]+/)
    .flatMap((part) => part.split(/(?<=[a-z0-9])(?=[A-Z])/))
    .filter((word) => word !== "");
}

// Exported Go name of a property or parameter: snake_case and camelCase to
// PascalCase, with initialisms in capitals (domain_id -> DomainID).
export function fieldName(name: string): string {
  const value = words(name)
    .map((word) => (INITIALISMS.has(word.toLowerCase()) ? word.toUpperCase() : word.charAt(0).toUpperCase() + word.slice(1)))
    .join("");
  return value === "" || /^[0-9]/.test(value) ? `N${value}` : value;
}

function exportedName(name: string): string {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error(`go: schema name ${name} is not an identifier`);
  return name.charAt(0).toUpperCase() + name.slice(1);
}

// Unexported Go identifier of a path parameter (domain_id -> domainID).
function argName(name: string): string {
  const parts = words(name);
  const first = parts[0] ?? "p";
  const head = INITIALISMS.has(first.toLowerCase()) ? first.toLowerCase() : first.charAt(0).toLowerCase() + first.slice(1);
  let value = parts.length > 1 ? head + fieldName(parts.slice(1).join("_")) : head;
  if (/^[0-9]/.test(value)) value = `p${value}`;
  return RESERVED_IDENTIFIERS.has(value) ? `${value}Value` : value;
}

// ---------------------------------------------------------------------- services

interface Method {
  op: IROperation;
  name: string;
  // Identifier of each path parameter, in template order.
  pathArgs: string[];
}

interface Service {
  field: string;
  typeName: string;
  methods: Method[];
}

function groupServices(operations: IROperation[]): Service[] {
  const services = new Map<string, Service>();
  for (const op of operations) {
    const parts = op.names.go.split(".");
    if (parts.length !== 2 || !parts.every((part) => /^[A-Z][A-Za-z0-9]*$/.test(part))) {
      throw new Error(`go: names.go ${op.names.go} of ${op.id} is not Resource.Method`);
    }
    const [field, name] = parts as [string, string];
    for (const parameter of op.headerParams) {
      if (parameter.name.toLowerCase() !== IDEMPOTENCY_HEADER) throw new Error(`go: header ${parameter.name} of ${op.id} is not supported`);
    }
    for (const parameter of op.queryParams) {
      if (parameter.style !== "form") throw new Error(`go: query parameter ${parameter.name} of ${op.id} has style ${parameter.style}`);
    }
    const pathArgs = op.pathParams.map((parameter) => argName(parameter.name));
    if (new Set(pathArgs).size !== pathArgs.length) throw new Error(`go: path parameters of ${op.id} give clashing argument names ${pathArgs.join(", ")}`);
    let service = services.get(field);
    if (service === undefined) {
      service = { field, typeName: `${field}Service`, methods: [] };
      services.set(field, service);
    }
    service.methods.push({ op, name, pathArgs });
  }
  for (const service of services.values()) {
    const taken = new Set<string>();
    for (const method of service.methods) {
      for (const name of method.op.pagination === null ? [method.name] : [method.name, `${method.name}All`]) {
        if (taken.has(name)) throw new Error(`go: method ${service.field}.${name} is generated twice`);
        taken.add(name);
      }
    }
  }
  return [...services.values()].sort((a, b) => (a.field < b.field ? -1 : a.field > b.field ? 1 : 0));
}

function opVar(service: Service, method: Method): string {
  return `op${service.field}${method.name}`;
}

function bodyKind(op: IROperation): "json" | "multipart" | null {
  if (op.requestBody === null) return null;
  const media = isObject(op.requestBody) ? op.requestBody["contentMediaType"] : undefined;
  if (media === undefined) return "json";
  if (media === "multipart/form-data") return "multipart";
  throw new Error(`go: request body ${String(media)} of ${op.id} is not supported`);
}

function bodySchema(op: IROperation): JsonSchema {
  const schema = op.requestBody!;
  // The media type annotation is not part of the value.
  return isObject(schema) && "contentMediaType" in schema ? Object.fromEntries(Object.entries(schema).filter(([key]) => key !== "contentMediaType")) : schema;
}

function bodyType(types: GoTypes, service: Service, method: Method): GoType {
  return types.resolve(bodySchema(method.op), `${service.field}${method.name}Body`);
}

function bodyParam(type: GoType): string {
  return type.kind === "struct" ? `*${type.expr}` : type.expr;
}

function responseType(types: GoTypes, service: Service, method: Method): string {
  const schema = method.op.response.schema;
  return schema === null ? "map[string]any" : types.resolve(schema, `${service.field}${method.name}Response`).expr;
}

// Item type of a paginated operation: the element of the `data` array of its response.
function pageItem(types: GoTypes, service: Service, method: Method): string {
  const { op } = method;
  const schema = op.response.schema;
  if (schema === null) return "any";
  const response = types.resolve(schema, `${service.field}${method.name}Response`);
  const property = types.shape(schema)?.get(op.pagination!.items);
  if (response.struct === null || property === undefined) return "any";
  const field = types.resolve(property.schema, `${response.struct}${fieldName(op.pagination!.items)}`);
  return field.kind === "slice" && field.expr.startsWith("[]") ? field.expr.slice(2) : "any";
}

// The values() method of a query struct: each set parameter as its query values.
function queryValues(name: string, parameters: IRParameter[], types: GoTypes): string {
  const lines = parameters.map((parameter) => {
    const field = fieldName(parameter.name);
    const type = types.resolve(parameter.schema, `${name}${field}`);
    const key = JSON.stringify(parameter.name);
    if (type.kind === "slice") return `\tif q.${field} != nil {\n\t\tvalues[${key}] = queryList(q.${field}, ${parameter.explode})\n\t}`;
    if (parameter.required && !type.nullable) return `\tvalues[${key}] = []string{queryText(q.${field})}`;
    return `\tif q.${field} != nil {\n\t\tvalues[${key}] = []string{queryText(*q.${field})}\n\t}`;
  });
  return `func (q *${name}) values() map[string][]string {
	values := map[string][]string{}
	if q == nil {
		return values
	}
${lines.join("\n")}
	return values
}
`;
}

function operationLiteral(service: Service, method: Method): string {
  const { op } = method;
  const kinds: Record<string, string> = { json: "bodyJSON", multipart: "bodyMultipart" };
  const body = kinds[bodyKind(op) ?? "none"] ?? "bodyNone";
  const query = `[]string{${op.queryParams.map((parameter) => JSON.stringify(parameter.name)).join(", ")}}`;
  return `var ${opVar(service, method)} = &operation{id: ${JSON.stringify(op.id)}, method: ${JSON.stringify(op.method)}, path: ${JSON.stringify(op.path)}, query: ${query}, body: ${body}}`;
}

function methodSource(service: Service, method: Method, types: GoTypes): string {
  const { op } = method;
  for (const parameter of op.pathParams) {
    const type = types.resolve(parameter.schema, `${service.field}${method.name}${fieldName(parameter.name)}`);
    if (type.expr !== "string") throw new Error(`go: path parameter ${parameter.name} of ${op.id} is not a string`);
  }
  const receiver = `func (s *${service.typeName})`;
  const params = ["ctx context.Context", ...method.pathArgs.map((arg) => `${arg} string`)];
  const path = method.pathArgs.length === 0 ? "nil" : `[]string{${method.pathArgs.join(", ")}}`;
  let body = "nil";
  if (op.requestBody !== null) {
    params.push(`body ${bodyParam(bodyType(types, service, method))}`);
    body = "body";
  }
  let query = "nil";
  if (op.queryParams.length > 0) {
    const name = `${service.field}${method.name}Query`;
    types.query(name, op.queryParams);
    types.append(queryValues(name, op.queryParams, types));
    params.push(`query *${name}`);
    query = "query.values()";
  }
  if (op.idempotency) params.push("options ...RequestOption");
  const response = responseType(types, service, method);
  const doc = [`${method.name} calls ${op.id}.`, ...(op.summary === null ? [] : ["", op.summary]), "", `operationId: \`${op.id}\` — \`${op.method} ${op.path}\``];
  let source = `${comment(doc, "")}${receiver} ${method.name}(${params.join(", ")}) (*${response}, error) {
	return request[${response}](ctx, s.core, ${opVar(service, method)}, ${path}, ${query}, ${body}, ${op.idempotency ? "options" : "nil"})
}
`;

  if (op.pagination !== null) {
    const pagination = op.pagination;
    const pageQuery = op.queryParams.filter((parameter) => parameter.name !== pagination.after && parameter.name !== pagination.before);
    const allParams = ["ctx context.Context", ...method.pathArgs.map((arg) => `${arg} string`)];
    let allQuery = "nil";
    if (pageQuery.length > 0) {
      const name = `${service.field}${method.name}AllQuery`;
      types.query(name, pageQuery);
      types.append(queryValues(name, pageQuery, types));
      allParams.push(`query *${name}`);
      allQuery = "query.values()";
    }
    const item = pageItem(types, service, method);
    const allDoc = [
      `${method.name}All iterates every item of every page of ${op.id}, following \`${pagination.after}\` while \`${pagination.hasMore}\` is true.`,
      "A page that keeps failing ends the iteration with its error and a zero item.",
      "",
      `operationId: \`${op.id}\` — \`${op.method} ${op.path}\``,
    ];
    source += `\n${comment(allDoc, "")}${receiver} ${method.name}All(${allParams.join(", ")}) iter.Seq2[${item}, error] {
	return paginate[${item}](ctx, s.core, ${opVar(service, method)}, ${path}, ${allQuery})
}
`;
  }
  return source;
}

function servicesFile(services: Service[], types: GoTypes): string {
  const constants = services.flatMap((service) => service.methods.map((method) => operationLiteral(service, method)));
  const blocks = services.map(
    (service) => `// ${service.typeName} holds the operations of ${service.methods[0]!.op.resource}.
type ${service.typeName} struct {
	core *core
}

${service.methods.map((method) => methodSource(service, method, types)).join("\n")}`,
  );
  const iter = services.some((service) => service.methods.some((method) => method.op.pagination !== null));
  return `${HEADER}// One method per operation of the IR; paginated operations also get <Method>All.

package resend

import (
	"context"
${iter ? '\t"iter"\n' : ""})

${constants.join("\n")}

${blocks.join("\n")}`;
}

function clientFile(services: Service[]): string {
  const fields = services.map((service) => `\t// ${service.field} holds the operations of ${service.methods[0]!.op.resource}.\n\t${service.field} *${service.typeName}`);
  const assignments = services.map((service) => `\t\t${service.field}: &${service.typeName}{core: c},`);
  return `${HEADER}package resend

// Client calls the Resend API; it has one service per resource of the specification.
type Client struct {
${fields.join("\n")}
}

// NewClient builds a client. The key defaults to RESEND_API_KEY, the base URL to
// RESEND_BASE_URL and the timeout of each attempt to RESEND_TIMEOUT_MS
// (vault/CONTRACT.md §5.1); without a key it returns an error.
func NewClient(options ...Option) (*Client, error) {
	c, err := newCore(options)
	if err != nil {
		return nil, err
	}
	return &Client{
${assignments.join("\n")}
	}, nil
}
`;
}

